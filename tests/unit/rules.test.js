test('issues come in the fixed order', () => {
  // A synthetic input that triggers many issues at once.
  const many = remember(Rules.issues({
    design: defaultDesign({ fgColor: '#cccccc', transparentBackground: true, logo: LOGO, logoSize: 0.5, errorCorrection: 'M' }),
    ecl: 'M',
    eclAuto: false,
    analysis: { version: 30 },
    type: 'URLText',
    exportOptions: exportOptions({ pixelSize: 512 }),
    physical: { widthMm: 10, codeMm: 8, moduleMm: 0.2, scanDistanceMm: 80 },
    pixels: { px: 512, pxPerModule: 2.5, capped: false, mode: 'pixels' },
    decode: 'pass-large'
  }));
  assert.deepEqual(ids(many), [
    'lowContrast', 'transparentBackground', 'denseData', 'printTooSmall', 'sizeTooSmall',
    'logoErrorCorrection', 'logoLarge', 'smallScanRisky'
  ]);

  const others = remember(Rules.issues({
    design: defaultDesign({ fgColor: '#ffffff', bgColor: '#000000', logo: LOGO, logoSize: 0.45, dotStyle: 'dots' }),
    ecl: 'M',
    eclAuto: false,
    analysis: { version: 16 },
    type: 'Payment',
    exportOptions: exportOptions({ format: 'svg' }, { enabled: true }),
    physical: { widthMm: 18, codeMm: 15, moduleMm: 0.6, scanDistanceMm: 150 },
    pixels: null,
    decode: 'fail'
  }));
  assert.deepEqual(ids(others), ['inverted', 'denseData', 'codeTooSmall', 'logoLarge', 'paymentLogo', 'decodeFailed']);
  assertCanonicalOrder(many);
  assertCanonicalOrder(others);
});

test('contrast issues: fail below 0.25, warn below 0.40, gradient and corner colors count', () => {
  const fail = remember(evaluate({ design: defaultDesign({ fgColor: '#eeeeee' }) }));
  assert.equal(fail[0].severity, 'fail');
  assert.deepEqual(fail[0].fix, {
    labelKey: 'scan.fixBlack',
    design: { fgColor: '#000000', bgColor: '#ffffff', fill: 'solid', customCorners: false, transparentBackground: false }
  });

  const warn = remember(evaluate({ design: defaultDesign({ fgColor: '#cccccc' }) }));
  assert.equal(warn[0].id, 'lowContrast');
  assert.equal(warn[0].severity, 'warn');

  const gradient = remember(evaluate({ design: defaultDesign({ fill: 'gradient', fgColor2: '#dddddd' }) }));
  assert.equal(gradient[0].messageKey, 'warnings.gradientContrast');

  const corners = remember(evaluate({
    design: defaultDesign({ customCorners: true, cornerOuterColor: '#000000', cornerInnerColor: '#f5f5f5' })
  }));
  assert.equal(corners[0].messageKey, 'warnings.gradientContrast');
  assert.equal(corners[0].severity, 'fail');

  // The second gradient stop is ignored while the fill is solid.
  assert.deepEqual(evaluate({ design: defaultDesign({ fgColor2: '#ffffff' }) }), []);
});

test('inverted colors warn and offer to swap them', () => {
  const list = remember(evaluate({ design: defaultDesign({ fgColor: '#ffffff', bgColor: '#102a43' }), decode: 'pass' }));
  assert.deepEqual(ids(list), ['inverted']);
  assert.equal(list[0].severity, 'warn');
  assert.deepEqual(list[0].fix, { labelKey: 'scan.fixSwapColors', design: { fgColor: '#102a43', bgColor: '#ffffff' } });
  assert.deepEqual(Rules.scanState(list, 'pass'), { state: 'warn', verified: true });

  // Low contrast wins over inverted.
  assert.deepEqual(ids(evaluate({ design: defaultDesign({ fgColor: '#222222', bgColor: '#000000' }) })), ['lowContrast']);
});

test('the swap fix is offered only when swapping gives a readable code', () => {
  // A light gradient on navy: swapping would leave the light second stop on
  // a white background, so black on white is offered instead.
  const gradient = defaultDesign({ fgColor: '#ffffff', bgColor: '#102a43', fill: 'gradient', fgColor2: '#eeeeee' });
  const list = remember(evaluate({ design: gradient, decode: 'pass' }));
  assert.deepEqual(ids(list), ['inverted']);
  assert.equal(list[0].fix.labelKey, 'scan.fixBlack');
  const swapped = evaluate({ design: { ...gradient, ...list[0].fix.design } });
  assert.deepEqual(swapped, []);

  // Custom corners that stay light also rule out the swap.
  const corners = defaultDesign({ fgColor: '#ffffff', bgColor: '#000000', customCorners: true, cornerOuterColor: '#ffffff', cornerInnerColor: '#f0f0f0' });
  assert.equal(evaluate({ design: corners })[0].fix.labelKey, 'scan.fixBlack');

  // A mid grey second stop reads on both backgrounds, so the swap is offered.
  const greyStop = defaultDesign({ fgColor: '#ffffff', bgColor: '#102a43', fill: 'gradient', fgColor2: '#b4b4b4' });
  const greyList = evaluate({ design: greyStop });
  assert.deepEqual(ids(greyList), ['inverted']);
  assert.equal(greyList[0].fix.labelKey, 'scan.fixSwapColors');
  assert.deepEqual(evaluate({ design: { ...greyStop, ...greyList[0].fix.design } }), []);
});

