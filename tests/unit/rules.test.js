test('decode results add smallScanRisky or decodeFailed', () => {
  const large = remember(evaluate({ decode: 'pass-large' }));
  assert.deepEqual(ids(large), ['smallScanRisky']);
  assert.deepEqual(Rules.scanState(large, 'pass-large'), { state: 'warn', verified: true });

  const failed = remember(evaluate({ design: defaultDesign({ dotStyle: 'dots' }), decode: 'fail' }));
  assert.deepEqual(ids(failed), ['decodeFailed']);
  assert.equal(failed[0].severity, 'fail');
  assert.deepEqual(failed[0].fix, {
    labelKey: 'scan.fixSquare',
    design: { dotStyle: 'square', cornerSquareStyle: 'square', cornerDotStyle: 'square' }
  });
  assert.deepEqual(Rules.scanState(failed, 'fail'), { state: 'fail', verified: false });

  // A fix that would change nothing is left out.
  const square = evaluate({
    design: defaultDesign({ cornerSquareStyle: 'square', cornerDotStyle: 'square' }),
    decode: 'fail'
  });
  assert.deepEqual(ids(square), ['decodeFailed']);
  assert.equal(square[0].fix, undefined);

  // A contrast or logo issue offers the likelier fix, so the shapes fix is
  // left out. jsQR cannot read #cccccc on white, for example.
  const grey = remember(evaluate({ design: defaultDesign({ fgColor: '#cccccc', dotStyle: 'dots' }), decode: 'fail' }));
  assert.deepEqual(ids(grey), ['lowContrast', 'decodeFailed']);
  assert.deepEqual(grey.map(issue => issue.severity), ['warn', 'fail']);
  assert.equal(grey[0].fix.labelKey, 'scan.fixBlack');
  assert.equal(grey[1].fix, undefined);

  const logo = evaluate({ design: defaultDesign({ logo: LOGO, logoSize: 0.5, dotStyle: 'dots' }), decode: 'fail' });
  assert.deepEqual(ids(logo), ['logoLarge', 'decodeFailed']);
  assert.equal(logo[1].fix, undefined);
});

test('a failed decode of a light code offers black on white, and never a fix that changes nothing', () => {
  const blackOnWhite = {
    labelKey: 'scan.fixBlack',
    design: { fgColor: '#000000', bgColor: '#ffffff', fill: 'solid', customCorners: false, transparentBackground: false }
  };
  // #aaaaaa passes the contrast warning, but jsQR cannot read it, so the
  // colors are the likelier cure than the shapes.
  const light = remember(evaluate({ design: defaultDesign({ fgColor: '#aaaaaa' }), decode: 'fail' }));
  assert.deepEqual(ids(light), ['decodeFailed']);
  assert.deepEqual(light[0].fix, blackOnWhite);

  // Square shapes already: black on white is the next step.
  const squareLight = evaluate({
    design: defaultDesign({ fgColor: '#aaaaaa', cornerSquareStyle: 'square', cornerDotStyle: 'square' }),
    decode: 'fail'
  });
  assert.deepEqual(squareLight[0].fix, blackOnWhite);

  // A dark colored code with fancy shapes still gets square shapes first,
  // and black on white once the shapes are square.
  const blue = evaluate({ design: defaultDesign({ fgColor: '#1e3a8a', dotStyle: 'dots' }), decode: 'fail' });
  assert.equal(blue[0].fix.labelKey, 'scan.fixSquare');
  const blueSquare = evaluate({
    design: defaultDesign({ fgColor: '#1e3a8a', cornerSquareStyle: 'square', cornerDotStyle: 'square' }),
    decode: 'fail'
  });
  assert.deepEqual(blueSquare[0].fix, blackOnWhite);
});

test('scanState: any fail gives fail, otherwise any warn gives warn', () => {
  const info = [{ id: 'transparentBackground', severity: 'info', messageKey: 'warnings.transparentBackground' }];
  assert.equal(Rules.scanState(info, 'pass').state, 'ok');
  assert.equal(Rules.scanState([...info, { severity: 'warn' }], 'pass').state, 'warn');
  assert.equal(Rules.scanState([{ severity: 'warn' }, { severity: 'fail' }], null).state, 'fail');
  assert.deepEqual(Rules.scanState([], undefined), { state: 'ok', verified: null });
});

test('every messageKey and labelKey exists in English', () => {
  const english = new Set(flattenKeys(loadTranslations().en));
  const keys = new Set();
  for (const issue of seenIssues) {
    keys.add(issue.messageKey);
    if (issue.fix) keys.add(issue.fix.labelKey);
  }

  const seenIds = new Set(seenIssues.map(issue => issue.id));
  assert.deepEqual(ISSUE_ORDER.filter(id => !seenIds.has(id)), [], 'every issue id is exercised');

  // Also every key literal in the source, including ones the tests miss.
  const source = fs.readFileSync(path.join(repoRoot, 'Public/js/lib/rules.js'), 'utf8');
  for (const match of source.matchAll(/'((?:warnings|scan)\.[A-Za-z0-9_.]+)'/g)) keys.add(match[1]);

  assert.deepEqual([...keys].filter(key => !english.has(key)), []);
});
