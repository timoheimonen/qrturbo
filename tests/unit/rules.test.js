const ISSUE_ORDER = [
  'lowContrast', 'inverted', 'transparentBackground', 'denseData', 'printTooSmall', 'codeTooSmall',
  'sizeTooSmall', 'logoErrorCorrection', 'logoLarge', 'paymentLogo', 'smallScanRisky', 'decodeFailed'
];

const LOGO = Object.freeze({
  dataUrl: 'data:image/png;base64,iVBORw0KGgo=',
  mime: 'image/png',
  name: 'logo.png',
  width: 64,
  height: 64,
  bytes: 8,
  optimized: false
});

function defaultDesign(patch = {}) {
  return {
    fgColor: '#000000',
    bgColor: '#ffffff',
    transparentBackground: false,
    fill: 'solid',
    fgColor2: '#2563eb',
    gradientType: 'linear',
    gradientAngle: 45,
    customCorners: false,
    cornerOuterColor: '#000000',
    cornerInnerColor: '#000000',
    errorCorrection: 'auto',
    dotStyle: 'square',
    cornerSquareStyle: 'extra-rounded',
    cornerDotStyle: 'dot',
    margin: 4,
    logo: null,
    logoSize: 0.4,
    logoPadding: 0.5,
    frameStyle: 'none',
    frameText: '',
    frameColor: '#000000',
    minVersion: 0,
    ...patch
  };
}

function exportOptions(patch = {}, print = {}) {
  return {
    v: 1,
    format: 'png',
    pixelSize: 1024,
    customPixels: 1024,
    print: { enabled: false, unit: 'mm', width: 50, dpi: 300, ...print },
    page: 'fit',
    colorMode: 'rgb',
    ...patch
  };
}

/**
 * Builds the issues() input the way QRTurboScan does: the effective level,
 * the physical and pixel sizes from the export options, and the decode.
 */
function evaluate({ design = defaultDesign(), type = 'URLText', version = 2, quietZone = 4, qrFraction = 1, options = exportOptions(), decode = null } = {}) {
  const { ecl, auto } = Rules.effectiveEcl(design, type);
  const moduleCount = 17 + (4 * version);
  const input = {
    design,
    ecl,
    eclAuto: auto,
    analysis: { mode: 'byte', length: 0, version, modules: moduleCount, usedBits: 0, fits: true, maxAtLevel: 0, roomInVersion: 0 },
    type,
    exportOptions: options,
    physical: Rules.physical(options, qrFraction, moduleCount, quietZone),
    pixels: Rules.pixels(options, qrFraction, moduleCount, quietZone),
    decode
  };
  return Rules.issues(input);
}

const ids = list => list.map(issue => issue.id);

function assertCanonicalOrder(list) {
  const positions = list.map(issue => ISSUE_ORDER.indexOf(issue.id));
  assert.ok(positions.every(position => position >= 0), `unknown id in ${ids(list)}`);
  assert.deepEqual(positions, [...positions].sort((a, b) => a - b), `out of order: ${ids(list)}`);
}

// Every issue generated by the tests below, for the translation check.
const seenIssues = [];
function remember(list) {
  seenIssues.push(...list);
  return list;
}

test('effectiveEcl covers auto, logos, explicit levels and Payment', () => {
  assert.deepEqual(Rules.effectiveEcl(defaultDesign(), 'URLText'), { ecl: 'M', auto: true });
  assert.deepEqual(Rules.effectiveEcl(defaultDesign({ logo: LOGO }), 'URLText'), { ecl: 'H', auto: true });
  assert.deepEqual(Rules.effectiveEcl(defaultDesign({ errorCorrection: 'Q' }), 'VCard'), { ecl: 'Q', auto: false });
  assert.deepEqual(Rules.effectiveEcl(defaultDesign({ errorCorrection: 'L', logo: LOGO }), 'Wifi'), { ecl: 'L', auto: false });
  assert.deepEqual(Rules.effectiveEcl(defaultDesign({ errorCorrection: 'H' }), 'Payment'), { ecl: 'M', auto: false });
  assert.deepEqual(Rules.effectiveEcl(defaultDesign({ logo: LOGO }), 'Payment'), { ecl: 'M', auto: false });
});

test('versionFloor uses an explicit floor or the design minimum, capped at 13 for Payment', () => {
  assert.equal(Rules.PAYMENT_MAX_VERSION, 13);
  assert.equal(Rules.versionFloor(defaultDesign(), 'URLText'), 1);
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 20 }), 'URLText'), 20);
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 20 }), 'URLText', 7), 7);
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 5 }), 'URLText', 41), 5);
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 2.5 }), 'URLText'), 1);
  assert.equal(Rules.versionFloor(null, 'URLText'), 1);

  // EPC069-12: a payment code never goes above version 13.
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 20 }), 'Payment'), 13);
  assert.equal(Rules.versionFloor(defaultDesign({ minVersion: 9 }), 'Payment'), 9);
  assert.equal(Rules.versionFloor(defaultDesign(), 'Payment', 40), 13);
  assert.equal(Rules.versionFloor(defaultDesign(), 'Payment'), 1);
});

