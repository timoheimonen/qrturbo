test('physical math: 50 mm, 33 modules and quiet zone 4 give 1.22 mm modules', () => {
  const size = Rules.physical(exportOptions({ format: 'pdf' }), 1, 33, 4);
  assert.equal(size.widthMm, 50);
  assert.equal(Number(size.moduleMm.toFixed(2)), 1.22);
  assert.ok(Math.abs(size.moduleMm - (50 / 41)) < 1e-12);
  assert.ok(Math.abs(size.codeMm - ((50 / 41) * 33)) < 1e-12);
  assert.ok(Math.abs(size.scanDistanceMm - (size.codeMm * 10)) < 1e-9);
});

test('physical size applies to PDF and EPS always, and to PNG, JPG and SVG in print mode', () => {
  assert.ok(Rules.physical(exportOptions({ format: 'eps' }), 1, 25, 4));
  assert.equal(Rules.physical(exportOptions({ format: 'png' }), 1, 25, 4), null);
  assert.equal(Rules.physical(exportOptions({ format: 'svg' }), 1, 25, 4), null);
  assert.ok(Rules.physical(exportOptions({ format: 'png' }, { enabled: true }), 1, 25, 4));
  assert.ok(Rules.physical(exportOptions({ format: 'jpg' }, { enabled: true }), 1, 25, 4));
  assert.ok(Rules.physical(exportOptions({ format: 'svg' }, { enabled: true }), 1, 25, 4));
  assert.equal(Rules.physical(exportOptions({ format: 'webp' }, { enabled: true }), 1, 25, 4), null);

  const inches = Rules.physical(exportOptions({ format: 'pdf' }, { unit: 'in', width: 2 }), 1, 25, 4);
  assert.ok(Math.abs(inches.widthMm - 50.8) < 1e-9);

  // Inside a frame the code covers only part of the printed width.
  const framed = Rules.physical(exportOptions({ format: 'pdf' }), 0.5, 25, 4);
  assert.ok(Math.abs(framed.moduleMm - (25 / 33)) < 1e-12);
});

test('pixel size follows the size select, the custom size and the print size', () => {
  const preset = Rules.pixels(exportOptions(), 1, 25, 4);
  assert.deepEqual({ ...preset, pxPerModule: Number(preset.pxPerModule.toFixed(4)) }, {
    px: 1024, pxPerModule: 31.0303, capped: false, mode: 'pixels'
  });
  assert.equal(Rules.pixels(exportOptions({ pixelSize: 'custom', customPixels: 300 }), 1, 25, 4).px, 300);

  const print = Rules.pixels(exportOptions({}, { enabled: true, width: 50, dpi: 300 }), 1, 25, 4);
  assert.equal(print.px, 591);
  assert.equal(print.mode, 'print');

  const capped = Rules.pixels(exportOptions({}, { enabled: true, width: 400, dpi: 600 }), 1, 25, 4);
  assert.equal(capped.px, 4096);
  assert.equal(capped.capped, true);

  // Custom sizes are clamped to 128-4096 px, like the exporter does.
  assert.equal(Rules.pixels(exportOptions({ pixelSize: 'custom', customPixels: 40 }), 1, 25, 4).px, 128);
  const customCapped = Rules.pixels(exportOptions({ pixelSize: 'custom', customPixels: 5000 }), 1, 25, 4);
  assert.deepEqual([customCapped.px, customCapped.capped], [4096, true]);

  // WebP has no print size, so it keeps the pixel size.
  assert.equal(Rules.pixels(exportOptions({ format: 'webp' }, { enabled: true }), 1, 25, 4).px, 1024);
  assert.equal(Rules.pixels(exportOptions({ format: 'svg' }), 1, 25, 4), null);
  assert.equal(Rules.pixels(exportOptions({ format: 'pdf' }), 1, 25, 4), null);
});

